import assert from 'node:assert/strict';
import { createDevtoolsBridge, installGlobalDevtoolsBridge } from '../packages/devtools/dist/index.js';
import { VXLanguageService } from '../packages/tooling/dist/index.js';
const bridge = createDevtoolsBridge('phase18');
const uninstall = installGlobalDevtoolsBridge(bridge);
const disposeState = bridge.register({ id: 'state:count', category: 'state', name: 'count', value: 0 });
bridge.update('state:count', 'state', { value: 2, status: 'ready' });
bridge.measure({ category: 'performance', name: 'render', value: 2.5, unit: 'ms' });
assert.equal(bridge.snapshot().entities[0]?.value, 2);
assert.equal(bridge.snapshot().metrics.length, 1);
disposeState(); uninstall();
assert.equal(bridge.snapshot().entities.length, 0);
const source = `#script\nstate count:Int=0\nderive doubled:Int=count*2\naction increment(){\ncount++\n}\n#end script\n#view\nView{\nText(count)\n}\n#end view\n`;
const service = new VXLanguageService();
service.open('file:///Counter.vx', source, 1);
assert.ok(service.semanticTokens('file:///Counter.vx').length > 0);
assert.ok(service.inlayHints('file:///Counter.vx').length > 0);
assert.ok(service.workspaceSymbols('count').some((entry) => entry.symbol.name === 'count'));
const offset = source.indexOf('count++');
assert.equal(service.definition('file:///Counter.vx', offset)?.name, 'count');
console.log('Phase 18 runtime verification passed.');
